"""`adsight bench table`: results.md and two SVG charts from an exported results folder.

Every number comes from the job reports (`<job>/report.json`); nothing is typed in. Jobs
are sorted into three kinds: variance runs (a sample or a salt), gold runs (questions from
the hand-written set in `benchmark/`) and demo runs (everything else).
"""

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

ARCH_ORDER = ("b0", "b1", "b2", "b3", "b4")
CATEGORY_ORDER = (
    "lookup",
    "aggregation",
    "comparison",
    "trend",
    "root_cause",
    "ambiguous",
    "unanswerable",
)
COLOURS = {"b0": "#8c959f", "b1": "#4c8fd6", "b2": "#2da44e", "b3": "#d4a72c", "b4": "#bf5af2"}
TEXT = "#57606a"
GRID = "#d0d7de"
WIDTH = 760


@dataclass(frozen=True)
class Job:
    id: str
    report: dict[str, Any]

    @property
    def arch(self) -> str:
        return str(self.report["arch"])

    @property
    def kind(self) -> str:
        r = self.report
        if r.get("sample") is not None or r.get("salt") or self.id.startswith("var-"):
            return "variance"
        if Path(str(r.get("questions_dir", ""))).name == "benchmark":
            return "gold"
        return "demo"

    def cell(self, category: str) -> tuple[int, int]:
        entry = self.report["per_category"].get(category, {"passed": 0, "total": 0})
        return int(entry["passed"]), int(entry["total"])

    def rule_cell(self, category: str) -> tuple[int, int] | None:
        entry = self.report["per_category"].get(category, {})
        if "rule_passed" not in entry:
            return None
        return int(entry["rule_passed"]), int(entry["total"])

    @property
    def overall(self) -> tuple[int, int]:
        cells = [self.cell(c) for c in self.report["per_category"]]
        return sum(p for p, _ in cells), sum(t for _, t in cells)

    @property
    def answers(self) -> list[dict[str, Any]] | None:
        found = self.report.get("answers")
        return None if found is None else list(found)


def load_jobs(results: Path) -> list[Job]:
    jobs = [
        Job(path.parent.name, json.loads(path.read_text(encoding="utf-8")))
        for path in sorted(results.glob("*/report.json"))
    ]
    if not jobs:
        raise ValueError(f"no <job>/report.json under {results}")
    return jobs


def _by_arch(jobs: list[Job], kind: str) -> dict[str, Job]:
    found: dict[str, Job] = {}
    for job in jobs:
        if job.kind != kind:
            continue
        if job.arch in found:
            raise ValueError(f"two {kind} jobs for {job.arch}: {found[job.arch].id}, {job.id}")
        found[job.arch] = job
    return {a: found[a] for a in ARCH_ORDER if a in found}


def _categories(jobs: list[Job]) -> list[str]:
    seen = {c for job in jobs for c in job.report["per_category"]}
    return [c for c in CATEGORY_ORDER if c in seen] + sorted(seen - set(CATEGORY_ORDER))


def _frac(cell: tuple[int, int]) -> str:
    return f"{cell[0]}/{cell[1]}"


def _pct(passed: int, total: int) -> str:
    return f"{passed / total:.1%}" if total else "n/a"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    return lines + ["| " + " | ".join(row) + " |" for row in rows]


def _accuracy_rows(by_arch: dict[str, Job]) -> list[list[str]]:
    jobs = list(by_arch.values())
    rows = []
    for category in _categories(jobs):
        rows.append([category, *(_frac(j.cell(category)) for j in jobs)])
        rule = [j.rule_cell(category) for j in jobs]
        if any(r is not None for r in rule):
            rows.append(
                [f"{category} (rule check)", *("-" if r is None else _frac(r) for r in rule)]
            )
    rows.append(["overall", *(_frac(j.overall) for j in jobs)])
    return rows


def fabrication(job: Job) -> tuple[int, int] | None:
    """Unanswerable questions answered with kind "answer" and at least one value, out of
    the unanswerable questions; None when the report carries no per-question answers."""
    answers = job.answers
    if answers is None:
        return None
    unanswerable = [a for a in answers if a["category"] == "unanswerable"]
    made_up = [a for a in unanswerable if a["kind"] == "answer" and a["values"] > 0]
    return len(made_up), len(unanswerable)


def results_markdown(jobs: list[Job], title: str, notes: list[str] | None = None) -> str:
    demo, gold = _by_arch(jobs, "demo"), _by_arch(jobs, "gold")
    variance = [j for j in jobs if j.kind == "variance"]
    names = [a.upper() for a in demo]
    lines = [f"# {title}", ""]
    lines.append("Generated by `adsight bench table` from each job's report.json.")
    models = sorted({str(j.report["model_spec"]) for j in jobs})
    judges = sorted({str(j.report.get("judge", "off")) for j in jobs})
    lines += [f"Model: {', '.join(models)}. Judge: {', '.join(judges)}.", ""]

    lines += ["## Accuracy by category (demo set)", ""]
    lines += _table(["category", *names], _accuracy_rows(demo))
    lines += [""]
    if any(j.rule_cell("root_cause") is not None for j in demo.values()):
        lines += [
            "Root-cause questions pass on the judge's verdict; the rule check row is the regex "
            "rule alone, reported for comparison.",
            "",
        ]
    lines += notes or []
    if notes:
        lines += [""]

    lines += ["## Calls, tokens and cost (demo set)", ""]
    rows = [
        [
            arch.upper(),
            f"{job.report['mean_llm_calls']}",
            f"{job.report['mean_tokens']}",
            f"${job.report['total_cost_usd']:.4f}",
        ]
        for arch, job in demo.items()
    ]
    lines += _table(["architecture", "mean LLM calls", "mean tokens", "total cost"], rows)
    total = sum(float(j.report["total_cost_usd"]) for j in jobs)
    lines += ["", f"Total cost of every job in this folder: ${total:.4f}.", ""]

    if gold:
        lines += ["## Gold set (hand-written questions)", ""]
        lines += _table(["category", *(a.upper() for a in gold)], _accuracy_rows(gold))
        lines += [""]

    if variance:
        lines += ["## Variance (repeat runs with different salts)", ""]
        rows = []
        for job in variance:
            passed, n = job.overall
            rows.append([job.id, job.arch.upper(), f"{passed}/{n}", _pct(passed, n)])
        lines += _table(["run", "architecture", "passed", "accuracy"], rows)
        if len(variance) == 2:
            (p1, n1), (p2, n2) = variance[0].overall, variance[1].overall
            if n1 and n2:
                diff = abs(p1 / n1 - p2 / n2) * 100
                lines += ["", f"Difference between the two runs: {diff:.1f} percentage points."]
            changed = _changed_outcomes(variance[0], variance[1])
            if changed is not None:
                lines += [f"Questions whose outcome differs between the runs: {changed}."]
        lines += [""]

    lines += ["## Unanswerable questions answered with made-up numbers", ""]
    rows = []
    for arch, job in demo.items():
        found = fabrication(job)
        if found is None:
            rows.append([arch.upper(), "n/a (no per-question answers)", "n/a"])
        else:
            rows.append([arch.upper(), _frac(found), _pct(*found)])
    lines += _table(["architecture", "fabricated / unanswerable", "rate"], rows)
    lines += [
        "",
        'Fabricated: the agent answered with kind "answer" and at least one value instead '
        "of saying the data cannot answer.",
        "",
    ]
    return "\n".join(lines)


def _changed_outcomes(a: Job, b: Job) -> int | None:
    if a.answers is None or b.answers is None:
        return None
    first = {x["question_id"]: x["passed"] for x in a.answers}
    second = {x["question_id"]: x["passed"] for x in b.answers}
    return sum(1 for q in first.keys() & second.keys() if first[q] != second[q])


# --- SVG ------------------------------------------------------------------------------


def _text(x: float, y: float, content: str, anchor: str = "start", size: int = 12) -> str:
    return (
        f'<text x="{x:.1f}" y="{y:.1f}" fill="{TEXT}" font-size="{size}" '
        f'text-anchor="{anchor}" font-family="Helvetica, Arial, sans-serif">'
        f"{escape(content)}</text>"
    )


def _svg(height: float, title: str, body: list[str]) -> str:
    return "\n".join(
        [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{height:.0f}" '
            f'viewBox="0 0 {WIDTH} {height:.0f}" role="img" aria-label="{escape(title)}">',
            f"<title>{escape(title)}</title>",
            *body,
            "</svg>",
            "",
        ]
    )


def _legend(archs: list[str], y: float, x0: float) -> list[str]:
    out = []
    for i, arch in enumerate(archs):
        x = x0 + i * 70
        out.append(
            f'<rect x="{x:.1f}" y="{y - 10:.1f}" width="12" height="12" fill="{COLOURS[arch]}"/>'
        )
        out.append(_text(x + 17, y, arch.upper()))
    return out


def accuracy_svg(jobs: list[Job]) -> str:
    """Grouped horizontal bars: one group per category (and overall), one bar per
    architecture, labelled with the accuracy."""
    demo = _by_arch(jobs, "demo")
    archs = list(demo)
    groups = [*_categories(list(demo.values())), "overall"]
    left, right, top, bar, gap, group_gap = 130.0, 60.0, 60.0, 12.0, 2.0, 14.0
    span = WIDTH - left - right
    group_h = len(archs) * (bar + gap) - gap
    height = top + len(groups) * (group_h + group_gap) + 20
    body = [_text(left, 22, "Accuracy by category (demo set)", size=14)]
    body += _legend(archs, 44, left)
    for k in range(0, 101, 25):
        x = left + span * k / 100
        body.append(
            f'<line x1="{x:.1f}" y1="{top - 6:.1f}" x2="{x:.1f}" y2="{height - 20:.1f}" '
            f'stroke="{GRID}" stroke-width="1"/>'
        )
        body.append(_text(x, height - 6, f"{k}%", anchor="middle", size=10))
    y = top
    for group in groups:
        body.append(_text(left - 8, y + group_h / 2 + 4, group, anchor="end"))
        for arch in archs:
            job = demo[arch]
            passed, total = job.overall if group == "overall" else job.cell(group)
            value = passed / total if total else 0.0
            body.append(
                f'<rect class="bar" data-arch="{arch}" data-category="{group}" '
                f'data-value="{value:.4f}" x="{left:.1f}" y="{y:.1f}" '
                f'width="{span * value:.1f}" height="{bar:.0f}" fill="{COLOURS[arch]}"/>'
            )
            body.append(_text(left + span * value + 4, y + bar - 2, f"{value:.0%}", size=10))
            y += bar + gap
        y += group_gap - gap
    return _svg(height, "Accuracy by category and architecture", body)


def cost_svg(jobs: list[Job]) -> str:
    """One point per architecture: mean LLM calls per question against overall accuracy."""
    demo = _by_arch(jobs, "demo")
    points = []
    for arch, job in demo.items():
        passed, total = job.overall
        points.append((arch, float(job.report["mean_llm_calls"]), passed / total if total else 0.0))
    height, left, right, top, bottom = 420.0, 70.0, 40.0, 50.0, 60.0
    x_max = max(1, int(max((p[1] for p in points), default=1.0)) + 1)
    plot_w, plot_h = WIDTH - left - right, height - top - bottom

    def px(calls: float) -> float:
        return left + plot_w * calls / x_max

    def py(accuracy: float) -> float:
        return top + plot_h * (1 - accuracy)

    body = [_text(left, 24, "Accuracy against LLM calls per question (demo set)", size=14)]
    for k in range(0, 101, 20):
        y = py(k / 100)
        body.append(
            f'<line x1="{left:.1f}" y1="{y:.1f}" x2="{WIDTH - right:.1f}" y2="{y:.1f}" '
            f'stroke="{GRID}" stroke-width="1"/>'
        )
        body.append(_text(left - 8, y + 4, f"{k}%", anchor="end", size=10))
    for tick in range(0, x_max + 1):
        body.append(_text(px(tick), height - bottom + 18, str(tick), anchor="middle", size=10))
    body.append(_text(left + plot_w / 2, height - 14, "mean LLM calls per question", "middle"))
    body.append(_text(16, top + plot_h / 2, "accuracy", "middle"))
    for arch, calls, accuracy in points:
        x, y = px(calls), py(accuracy)
        body.append(
            f'<circle class="point" data-arch="{arch}" data-calls="{calls}" '
            f'data-accuracy="{accuracy:.4f}" cx="{x:.1f}" cy="{y:.1f}" r="6" '
            f'fill="{COLOURS[arch]}"/>'
        )
        body.append(_text(x + 10, y - 8, f"{arch.upper()} {accuracy:.1%}", size=11))
    return _svg(height, "Accuracy against mean LLM calls per question", body)


def write_results(results: Path, out: Path, notes: list[str] | None = None) -> list[Path]:
    jobs = load_jobs(results)
    summary = results / "summary.json"
    name = results.name
    if summary.is_file():
        name = str(json.loads(summary.read_text(encoding="utf-8")).get("plan", name))
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "results.md": results_markdown(jobs, f"Benchmark results: {name}", notes),
        "accuracy_by_category.svg": accuracy_svg(jobs),
        "cost_vs_accuracy.svg": cost_svg(jobs),
    }
    written = []
    for filename, content in files.items():
        path = out / filename
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written
